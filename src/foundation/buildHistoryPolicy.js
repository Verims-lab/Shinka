import { isValidMarker, markerNumber, ACTIVE_PACKAGE_LIMIT } from './buildMarkerRules.js';

export { ACTIVE_PACKAGE_LIMIT } from './buildMarkerRules.js';

// A continuation replaces that package's concise fields; it never appends a new package.
export function retainBuildPackages(entries, currentMarker) {
  if (!isValidMarker(currentMarker)) throw new Error('BUILD_MARKER_INVALID_FORMAT');
  const byMarker = new Map();
  for (const entry of entries) {
    if (!isValidMarker(entry?.build_marker)) throw new Error('BUILD_MARKER_INVALID_FORMAT');
    if (markerNumber(entry.build_marker) > markerNumber(currentMarker)) throw new Error('LEDGER_FUTURE_PACKAGE');
    byMarker.set(entry.build_marker, { ...byMarker.get(entry.build_marker), ...entry });
  }
  if (!byMarker.has(currentMarker)) throw new Error('LEDGER_HEAD_NOT_CANONICAL');
  return [...byMarker.values()].sort((a, b) => markerNumber(a.build_marker) - markerNumber(b.build_marker)).slice(-ACTIVE_PACKAGE_LIMIT);
}

export function renderBuildHistory(entries, currentMarker) {
  const current = entries.at(-1);
  return `# SHINKA — Build History\n\n**Document:** SHINKA_BUILD_HISTORY.md\n**Status:** ACTIVE — latest five unique packages\n**Current BuildMarker:** ${currentMarker}\n**Last Updated:** ${current.updated_at || current.created_at}\n**Authoritative Source References:** src/foundation/buildMarker.js, src/foundation/buildLedgerData.js\n**Purpose:** Generated, bounded active package history.\n**Scope:** Latest five packages including current; Git retains older history.\n\nGenerated by scripts/recordBuild.mjs. Update a package through that command; same-marker updates replace its concise summary. Older active entries are removed automatically when the sixth unique package is recorded. Product decisions remain in the active canonical standards. This policy never deletes security/audit records, user data or Health evidence.\n\n${entries.map(e => `## ${e.build_marker} — ${e.package_name} (${e.created_at})\n\n${e.short_summary}\n\nHealth: ${e.health_catalog_version}. Verification: ${e.full_health_status}.\n\n${e.notes}`).join('\n\n')}\n`;
}
