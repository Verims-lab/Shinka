import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { syntaxNodes } from '../src/foundation/inspection/sourceRules.js';

// Audit the executed catalog against its actual registration expressions. This
// records source predicates and observed evidence, never infers live behavior.
export async function writeHealthAudit(root, directory, registry, report, tests) {
  const sources=new Map(), folder=path.join(root,'src/foundation/health/cases');
  for(const file of await readdir(folder)) {
    if(!file.endsWith('.js'))continue;
    const code=await readFile(path.join(folder,file),'utf8');
    for(const node of syntaxNodes(code).filter(n=>n.type==='CallExpression')) {
      const id=node.arguments?.find(arg=>arg.type==='Literal' && /^H\d{2}-\d{3}$/.test(arg.value))?.value;
      if(!id)continue;
      sources.set(id,{file:`src/foundation/health/cases/${file}`,line:code.slice(0,node.start).split('\n').length,
        registration:code.slice(node.start,node.end),sha256:createHash('sha256').update(code).digest('hex')});
    }
  }
  const cases=await Promise.all(registry.map(async def=>{
    const result=report.cases.find(row=>row.id===def.id);
    const source=sources.get(def.id) || (/^H12-0(0[1-9]|1[0-9]|20)$/.test(def.id) ? {file:'src/foundation/health/cases/h12.js',line:9,registration:await readFile(path.join(folder,'h12.js'),'utf8')} : null);
    if(!source)throw new Error(`Missing audit source ${def.id}`);
    if(def.active && !def.hasRunner)throw new Error(`Missing runner ${def.id}`);
    return {...def,source,result:result?{status:result.status,assertion:result.assertion,evidence:result.evidence,execution:result.execution}:null,
      evidenceEnvironment:result?(def.classification==='STATIC'?'BUILD_TIME_STATIC':def.runnerType==='BACKEND'?'LOCAL_STUB_BACKEND_UNAVAILABLE':'LOCAL_BROWSER_SYNTHETIC_OR_DOM'):'SEPARATE_ACCEPTANCE_REQUIREMENT'};
  }));
  await mkdir(directory,{recursive:true});
  await writeFile(path.join(directory,'case-audit.json'),JSON.stringify({buildMarker:report.buildMarker,catalog:report.healthCatalogVersion,cases,tests},null,2)+'\n');
  const cell=value=>String(value).replaceAll('|','\\|').replaceAll('\n',' ');
  const lines=['# Executable Health audit — '+report.healthCatalogVersion,'','Generated by scripts/auditHealthCatalog.mjs from the actual runtime registry, source registrations and isolated local run. Full predicates, expected/actual values, evidence classes and versions: [case-audit.json](case-audit.json). BLOCKED backend prerequisites are not hosted failures or inferred success.','',
    '| ID | Requirement / claim | Actual control and assertion | Evidence / environment |','|---|---|---|---|'];
  for(const row of cases) lines.push(`| ${row.id} | ${cell(row.description)} | [${row.runnerType}: ${cell(row.title)}](../../../../${row.source.file}#L${row.source.line}) — ${row.active?'predicate and evidence captured in JSON':row.executionLocation+' / tracked, not dispatched'} | ${row.result?.status||'NOT EXECUTED'} · ${row.evidenceEnvironment} |`);
  await writeFile(path.join(directory,'case-audit.md'),lines.join('\n')+'\n');
}
